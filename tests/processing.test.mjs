import {test} from 'node:test';
import assert from 'node:assert/strict';
import {chromium,expect} from '@playwright/test';
import {PrismaClient} from '@prisma/client';
import {randomBytes,createHash} from 'node:crypto';
import {existsSync,mkdirSync} from 'node:fs';

test('Processing board: desktop drag, touch drag, saved history, search and navigation', {timeout:120000}, async()=>{
  const db=new PrismaClient();
  const browser=await chromium.launch({headless:true,executablePath:['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync)});
  let shop;
  try {
    const anonymous=await browser.newPage();
    await anonymous.goto('http://127.0.0.1:3000/processing');
    await expect(anonymous).toHaveURL(/\/login/); await anonymous.close();
    shop=await db.shop.create({data:{name:'Kanban test',email:`kanban-${Date.now()}@example.com`,passwordHash:'unused',accessStatus:'active'}});
    const customer=await db.customer.create({data:{shopId:shop.id,code:'KH1',name:'Khách thử nghiệm',phone:'0000000000',address:'',identityKey:'test'}});
    const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Ho_Chi_Minh'}).format(new Date());
    const day=(n)=>{const d=new Date(today+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+n);return d.toISOString().slice(0,10);};
    await db.order.createMany({data:Array.from({length:12},(_,i)=>({shopId:shop.id,customerId:customer.id,code:`DH${String(i).padStart(3,'0')}`,product:['Bó hoa hồng pastel','Giỏ hoa hướng dương','Hoa ly trắng'][i%3],customer:'Khách thử nghiệm',phone:'0000000000',address:'Địa chỉ thử nghiệm',note:'Giao hoa nhẹ nhàng, kèm thiệp chúc mừng.',date:day([0,1,6,7][i]??8),time:'09:00',orderDate:'2026-10-12',orderTime:'10:00',price:450000,paidAmount:100000,status:['pending','preparing','delivering','done'][Math.floor(i/3)]}))});
    const context=await browser.newContext({viewport:{width:1440,height:1000},hasTouch:true});
    const token=randomBytes(32).toString('hex');
    await db.session.create({data:{id:createHash('sha256').update(token).digest('hex'),shopId:shop.id,expiresAt:new Date(Date.now()+600000)}});
    await context.addCookies([{name:'floralhelp_session',value:token,url:'http://127.0.0.1:3000'}]);
    const page=await context.newPage();
    await page.goto('http://127.0.0.1:3000/orders');
    await page.getByRole('button',{name:'Xử Lí đơn',exact:true}).click();
    await expect(page).toHaveURL(/\/processing$/);
    await expect(page.locator('.processing-card')).toHaveCount(1);
    await page.getByRole('button',{name:'Ngày mai',exact:true}).click();
    await expect(page.locator('.processing-card')).toHaveCount(1);
    await expect(page.locator('.processing-card')).toContainText('DH001');
    await page.getByRole('button',{name:'7 ngày tới',exact:true}).click();
    await expect(page.locator('.processing-card')).toHaveCount(3);
    await page.getByRole('button',{name:'Khoảng ngày',exact:true}).click();
    const range=page.getByRole('form',{name:'Khoảng ngày giao hoa'});
    await range.getByLabel('Từ ngày',{exact:true}).fill(day(1));
    await range.getByLabel('Đến ngày',{exact:true}).fill(day(6));
    await expect(page.locator('.processing-card')).toHaveCount(3);
    await range.getByRole('button',{name:'Áp dụng'}).click();
    await expect(page.locator('.processing-card')).toHaveCount(2);
    await page.getByRole('button',{name:'Tất cả',exact:true}).click();
    const column=status=>page.locator(`[data-processing-column="${status}"]`);
    await expect(column('pending').locator('article')).toHaveCount(3);
    const source=await page.getByRole('article',{name:'Đơn DH000',exact:true}).locator('.processing-products').boundingBox();
    const target=await column('preparing').boundingBox();
    await page.mouse.move(source.x+source.width/2,source.y+source.height/2);
    await page.mouse.down();
    await page.mouse.move(target.x+target.width/2,target.y+100,{steps:12});
    await page.mouse.up();
    await expect(column('preparing').getByRole('article',{name:'Đơn DH000',exact:true})).toBeVisible();
    await expect(column('pending').locator('article')).toHaveCount(2);
    const moved=await db.order.findFirstOrThrow({where:{shopId:shop.id,code:'DH000'}});
    assert.equal(moved.status,'preparing'); assert.equal(moved.paidAmount,100000);
    const history=await db.orderHistory.findFirstOrThrow({where:{orderId:moved.id}});
    assert.equal(history.actorId,shop.id);
    await page.reload();
    await page.getByRole('button',{name:'Tất cả',exact:true}).click();
    await expect(column('preparing').getByRole('article',{name:'Đơn DH000',exact:true})).toBeVisible();
    await page.getByLabel('Tìm đơn cần xử lí').fill('DH000');
    await expect(page.locator('.processing-card')).toHaveCount(1);
    await page.getByLabel('Tìm đơn cần xử lí').fill('');
    mkdirSync('artifacts',{recursive:true});
    await page.screenshot({path:'artifacts/processing-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.locator('.processing-board').scrollIntoViewIfNeeded();
    const handle=await page.getByRole('button',{name:'Kéo đơn DH001',exact:true}).boundingBox();
    const touch=await context.newCDPSession(page);
    const y=handle.y+handle.height/2;
    await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:handle.x+handle.width/2,y}]});
    await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:345,y}]});
    await expect.poll(()=>page.locator('.processing-board').evaluate(el=>el.scrollLeft)).toBeGreaterThan(140);
    await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:275,y}]});
    await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await expect.poll(async()=> (await db.order.findFirstOrThrow({where:{shopId:shop.id,code:'DH001'}})).status).toBe('preparing');
    await page.locator('.processing-board').evaluate(el=>{el.scrollLeft=0;});
    const mobileSelect=column('pending').getByLabel('Trạng thái đơn DH002');
    await mobileSelect.selectOption('done');
    await expect.poll(async()=> (await db.order.findFirstOrThrow({where:{shopId:shop.id,code:'DH002'}})).status).toBe('done');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'artifacts/processing-mobile.png',fullPage:true});
  } finally {
    await browser.close();
    if(shop) await db.shop.delete({where:{id:shop.id}});
    await db.$disconnect();
  }
});
